/* ============================================================
   Site Config Generator — Pakistan MCQs Hub
   Computes the TRUE dataset counts from the actual data files and
   writes data/site-config.json, the single source of truth for
   every count, URL and API endpoint used across the project.
   Usage: node scripts/update-site-config.cjs
   ============================================================ */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "data", "site-config.json");

const SITE = {
  name: "Pakistan MCQs Hub",
  baseUrl: "https://jjjffdfde.github.io/pakistan-mcqs/",
  language: "en",
  copyrightYear: new Date().getFullYear()
};

const API = {
  /* Development base used by the self-hosted runtime-v2 server. */
  development: "http://localhost:8766",
  /* Production API base. Empty string = no public backend deployed;
     the frontend disables server-backed features cleanly. */
  production: ""
};

function countData(name) {
  const p = path.join(ROOT, "data", name + ".json");
  if (!fs.existsSync(p)) return null;
  const d = JSON.parse(fs.readFileSync(p, "utf8"));
  const arr = Array.isArray(d) ? d : (d.items || d.data || []);
  return arr.length;
}

function distinctField(name, field) {
  const p = path.join(ROOT, "data", name + ".json");
  if (!fs.existsSync(p)) return null;
  const d = JSON.parse(fs.readFileSync(p, "utf8"));
  const arr = Array.isArray(d) ? d : (d.items || d.data || []);
  return new Set(arr.map((x) => String((x[field] || "").toLowerCase()).trim()).filter(Boolean)).size;
}

const STATIC = {
  mcqs: countData("mcqs"),
  subjects: countData("subjects"),
  chapters: countData("chapters"),
  topics: countData("topics"),
  papers: countData("papers"),
  quizzes: countData("quizzes"),
  mockTests: countData("mock_tests"),
  exams: countData("exams"),
  categories: countData("categories"),
  programs: countData("programs"),
  mcqSubjects: distinctField("mcqs", "subject"),
  mcqChapters: distinctField("mcqs", "chapter"),
  mcqTopics: distinctField("mcqs", "topic")
};

const FULL = { questions: null, subjects: null, chapters: null, topics: null };
try {
  const Q = require(path.join(ROOT, "runtime-v2", "query-engine.cjs"));
  const L = require(path.join(ROOT, "runtime-v2", "data-loader.cjs"));
  if (fs.existsSync(path.join(ROOT, "runtime-v2", "indexes", "manifest.json"))) {
    /* async work — see build() below */
  }
} catch (e) { /* indexes not available (fresh clone without payload) */ }

async function main() {
  if (fs.existsSync(path.join(ROOT, "runtime-v2", "indexes", "manifest.json"))) {
    try {
      const Q = require(path.join(ROOT, "runtime-v2", "query-engine.cjs"));
      const L = require(path.join(ROOT, "runtime-v2", "data-loader.cjs"));
      await Q.init();
      const bySub = L.bySubjectActive();
      FULL.questions = Object.values(bySub).reduce((a, b) => a + b, 0);
      FULL.subjects = (await Q.subjects()).length;
      FULL.chapters = Q.chapters().length;
      FULL.topics = Q.topics().length;
    } catch (e) {
      console.warn("WARN: could not read runtime indexes:", e.message);
    }
  } else {
    console.warn("WARN: runtime-v2/indexes not present — full-database counts left as null.");
  }

  const config = {
    _comment: "AUTHORITATIVE SITE CONFIGURATION — generated by scripts/update-site-config.cjs. Do not edit by hand; rerun the generator after data changes.",
    site: SITE,
    api: API,
    dataset: {
      staticBank: {
        label: "Static practice bank (works instantly in the browser)",
        mcqs: STATIC.mcqs,
        subjects: STATIC.subjects,
        chapters: STATIC.chapters,
        topics: STATIC.topics,
        papers: STATIC.papers,
        quizzes: STATIC.quizzes,
        mockTests: STATIC.mockTests,
        exams: STATIC.exams,
        categories: STATIC.categories,
        programs: STATIC.programs,
        usedByMcqs: { subjects: STATIC.mcqSubjects, chapters: STATIC.mcqChapters, topics: STATIC.mcqTopics }
      },
      fullDatabase: {
        label: "Full database (self-hosted runtime-v2 server)",
        questions: FULL.questions,
        subjects: FULL.subjects,
        chapters: FULL.chapters,
        topics: FULL.topics
      }
    },
    generatedAt: new Date().toISOString(),
    generator: "scripts/update-site-config.cjs"
  };

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, JSON.stringify(config, null, 2) + "\n");
  console.log("Wrote data/site-config.json");
  console.log("  static bank:", JSON.stringify(STATIC));
  console.log("  full database:", JSON.stringify(FULL));
}

main().catch((e) => { console.error(e); process.exit(1); });
